WHENEVER SQLERROR EXIT SQL.SQLCODE
SET ECHO OFF FEEDBACK OFF VERIFY OFF

ALTER SESSION SET CONTAINER = FREEPDB1;

BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE DBSCANNER_SCANNER.SAMPLE_ASSETS (
      ASSET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ASSET_NAME VARCHAR2(128) NOT NULL,
      ASSET_CLASS VARCHAR2(64) NOT NULL,
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN
      RAISE;
    END IF;
END;
/

MERGE INTO DBSCANNER_SCANNER.SAMPLE_ASSETS target
USING (
  SELECT 'payments-api' AS ASSET_NAME, 'application' AS ASSET_CLASS FROM DUAL
  UNION ALL
  SELECT 'reporting-job' AS ASSET_NAME, 'batch' AS ASSET_CLASS FROM DUAL
) source
ON (target.ASSET_NAME = source.ASSET_NAME)
WHEN NOT MATCHED THEN
  INSERT (ASSET_NAME, ASSET_CLASS)
  VALUES (source.ASSET_NAME, source.ASSET_CLASS);

GRANT SELECT_CATALOG_ROLE TO DBSCANNER_SCANNER;
GRANT AUDIT_VIEWER TO DBSCANNER_SCANNER;

COMMIT;
